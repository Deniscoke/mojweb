/**
 * SCANS — real captured point clouds the point-scan engine may draw.
 * ==================================================================
 * Rule 1 of docs/motion-depth-plan.md: every 3D object on the site is real.
 * An entry here is a capture Denis made himself, decimated by
 * `scripts/build-scans.mjs` into the files under public/assets/scans/. Every
 * shipped point is one of the capture's own vertices; nothing is generated.
 *
 * Nothing renders unless `approvedByDenis` is true, so switching a scan off
 * is one boolean. The fields between `build-scans:begin/end` markers are
 * rewritten by the script; everything else is written by a person.
 *
 * Plain data plus two tiny lookups and no runtime imports, so it can be read
 * by Astro components and by scripts alike. Components must still check the
 * files exist at build time (`existsSync` on `public/<file>`), so a missing
 * or stale build renders no host and no caption rather than a broken canvas.
 */

import type { LocaleCode } from '~/i18n/locales';

export type ScanPlacement = 'hero' | `poster:${string}`;

export type Vec3 = [number, number, number];

export interface ScanSpec {
  id: string;
  /** Where it may appear: the homepage hero, or a project's embed poster. */
  placement: ScanPlacement;
  /** Public URLs. The desktop file is never requested on touch devices. */
  files: { desktop: string; mobile: string };
  /** Vertices in the source capture, and points shipped per tier. */
  pointCount: { source: number; desktop: number; mobile: number };
  /** Metres, Y up, centred on x/z, standing on y = 0. Same as the .bin header. */
  bounds: { min: Vec3; max: Vec3 };
  /** `measured` = luminance from the capture's own colours; `constant` = geometry only. */
  luminance: 'measured' | 'constant';
  /**
   * The mono caption under the scan (CSS uppercases it). Short, factual, and
   * never a claim that is not on record: no place or year until Denis gives
   * them. Missing locales fall back to English.
   */
  caption: { en: string } & Partial<Record<LocaleCode, string>>;
  /** Locale-relative path of the page the scan comes from, e.g. `lab/digital-space/`. */
  href: string;
  credit: string;
  /**
   * The gate. False means the build renders nothing for this scan: no host,
   * no caption, no request for the file.
   */
  approvedByDenis: boolean;
}

