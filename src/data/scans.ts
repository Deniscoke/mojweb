/** The approved scan for a placement, or undefined. Unapproved scans do not exist to the site. */
export function getScan(placement: ScanPlacement): ScanSpec | undefined {
  return SCANS.find((s) => s.placement === placement && s.approvedByDenis);
}

export function scanCaption(scan: ScanSpec, lang: string): string {
  return scan.caption[lang as LocaleCode] ?? scan.caption.en;
}
